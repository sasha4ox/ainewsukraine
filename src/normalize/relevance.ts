const WORD = String.raw`(?<![\p{L}\p{N}])`;
const WORD_END = String.raw`(?![\p{L}\p{N}])`;

const UKRAINE_RE = new RegExp(
  [
    "україн",
    "ukraine",
    "ukrainian",
    "зеленськ",
    "zelensk",
    `${WORD}зсу${WORD_END}`,
    "генштаб",
    "general staff",
    "збройн\\w{0,8}\\s+сил",
    "сили оборони",
    "повітряні сили",
    "нацгвард",
    "ки[їє]в",
    "kyiv",
    `${WORD}kiev${WORD_END}`,
    "харків",
    "kharkiv",
    "одес",
    "odesa",
    "odessa",
    "дніпр",
    "dnipr",
    "львів",
    `${WORD}lviv${WORD_END}`,
    "запоріж",
    "zaporizh",
    "херсон",
    "kherson",
    "микола[їє]в",
    "mykolaiv",
    "чернігів",
    "chernihiv",
    "полтав",
    "poltava",
    "вінниц",
    `${WORD}крим(?!інал)`,
    "crimea",
    "донецьк",
    "donetsk",
    "луганськ",
    "luhansk",
    "донбас",
    "donbas",
    "маріупол",
    "mariupol",
    "покровськ",
    "pokrovsk",
    "костянтинів",
    "олешк",
    "іскандер",
    "iskander",
    "шахед",
    "бпла",
    "приліт",
    "окупац",
    `${WORD}нбу${WORD_END}`,
    "нацбанк",
    "обліков\\w{0,6}\\s+ставк",
    "верховн\\w{0,6}\\s+рад",
    "кабмін",
    "рнбо",
    `${WORD}дснс${WORD_END}`,
    "starlink",
    "starshield",
    "гривн",
  ].join("|"),
  "iu",
);

/** True when a report is about Ukraine, the war, or a Ukrainian institution. */
export function isUkraineRelevant(text: string): boolean {
  return UKRAINE_RE.test(text);
}
